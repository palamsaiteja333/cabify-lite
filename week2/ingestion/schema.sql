/*
Cabify-Lite Week 2 - RAG document storage

Purpose:
- Store chunked policy documents
- Store Titan embeddings in pgvector
- Preserve citation metadata
- Support idempotent ingestion
- Support cosine similarity search using HNSW

Retrieval flow:
question
  -> Titan embedding
  -> cosine search against doc_chunks.embedding
  -> top-k chunks
  -> original content + metadata
  -> LLM
  -> answer with citations
*/

-- Enable the pgvector extension inside PostgreSQL.
-- This adds the VECTOR data type, vector distance operators,
-- and vector indexes like HNSW / IVFFlat.
CREATE EXTENSION IF NOT EXISTS vector;


-- Store document chunks used by the RAG system.
-- One row = one chunk of one source document.
CREATE TABLE IF NOT EXISTS doc_chunks (

    -- Auto-incrementing unique ID for each chunk.
    -- Useful for retrieval results, tracing, logging, and references.
    chunk_id BIGSERIAL PRIMARY KEY,


    -- Original document filename.
    -- Example: refunds_and_cancellations.md
    -- Important for citations and metadata filtering.
    source_file TEXT NOT NULL,


    -- Section or heading where this chunk came from.
    -- Example: "Rider Cancellation"
    -- Helps produce more precise citations and context.
    section_heading TEXT,


    -- Position of this chunk inside the source document.
    -- Example: 0, 1, 2, 3...
    -- Useful for preserving order and retrieving neighboring chunks.
    chunk_index INTEGER NOT NULL,


    -- Original human-readable text of the chunk.
    -- This is what gets sent to the LLM after retrieval.
    content TEXT NOT NULL,


    -- Deterministic hash/fingerprint of the chunk text.
    -- Used to make ingestion idempotent and avoid duplicates
    -- when the ingestion pipeline is run again.
    content_hash TEXT NOT NULL,


    -- Semantic embedding generated by Amazon Titan Text Embeddings V2.
    -- We configured Titan to return 1024-dimensional vectors.
    -- This column is used for semantic similarity search.
    embedding VECTOR(1024) NOT NULL,


    -- Timestamp showing when this chunk was inserted.
    -- Useful for auditing, reindexing, and debugging ingestion runs.
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),


    -- Prevent the same exact chunk from being inserted twice
    -- for the same source document.
    --
    -- Same content may still legitimately appear in a different file.
    UNIQUE (source_file, content_hash)
);


-- Vector similarity index.
--
-- HNSW = Hierarchical Navigable Small World.
-- Used for fast approximate nearest-neighbor search.
--
-- vector_cosine_ops tells pgvector that we intend to search
-- this embedding column using cosine distance.
CREATE INDEX IF NOT EXISTS doc_chunks_embedding_hnsw_idx
ON doc_chunks
USING hnsw (embedding vector_cosine_ops);


-- Normal PostgreSQL B-tree index on source_file.
-- Useful for metadata filtering, for example:
--   WHERE source_file = 'no_show_policy.md'
-- This is separate from the vector index.
CREATE INDEX IF NOT EXISTS doc_chunks_source_file_idx
ON doc_chunks (source_file);


-- content is for the LLM, embedding is for retrieval, and metadata is for citations/debugging.